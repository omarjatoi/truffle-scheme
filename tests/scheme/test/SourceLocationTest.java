package scheme.test;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertThrows;
import static org.junit.Assert.assertTrue;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;

import org.graalvm.polyglot.Context;
import org.graalvm.polyglot.PolyglotException;
import org.graalvm.polyglot.Source;
import org.graalvm.polyglot.SourceSection;
import org.junit.Rule;
import org.junit.Test;
import org.junit.rules.TemporaryFolder;

import scheme.launcher.SchemeMain;

/**
 * M3-09: source locations (design.md D13). Generated bytecode carries Bytecode DSL source sections,
 * so a guest stack trace names file, line and column for every Scheme frame, and syntax errors
 * name the file.
 */
public class SourceLocationTest {

    private static final String SCHEME = "scheme";

    @Rule public TemporaryFolder folder = new TemporaryFolder();

    /** "name:line:column" for each guest frame with a location, innermost first. */
    private static List<String> locations(PolyglotException e) {
        List<String> result = new ArrayList<>();
        for (PolyglotException.StackFrame frame : e.getPolyglotStackTrace()) {
            SourceSection s = frame.getSourceLocation();
            if (frame.isGuestFrame() && s != null) {
                result.add(s.getSource().getName() + ":" + s.getStartLine() + ":" + s.getStartColumn());
            }
        }
        return result;
    }

    private static PolyglotException error(Context context, Source source) {
        PolyglotException e = assertThrows(PolyglotException.class, () -> context.eval(source));
        assertTrue(e.getMessage(), e.isGuestException());
        return e;
    }

    @Test
    public void runtimeErrorsHaveLocatedFrames() throws IOException {
        Source source = Source.newBuilder(SCHEME, """
                        (define (f x)
                          (vector-ref x 1))
                        (define (g x)
                          (+ 1 (f x)))
                        (display (g (vector 1)))
                        """, "prog.scm").build();
        try (Context context = Context.create(SCHEME)) {
            List<String> frames = locations(error(context, source));
            // g's call of f (where f's tail call of vector-ref fails), and the program's call of g.
            assertTrue(frames.toString(), frames.contains("prog.scm:4:8"));
            assertTrue(frames.toString(), frames.contains("prog.scm:5:10"));
            // Every Scheme frame has a location: the prelude's raise too.
            for (PolyglotException.StackFrame frame : error(context, source).getPolyglotStackTrace()) {
                if (frame.isGuestFrame() && !frame.getRootName().startsWith("%")) {
                    assertTrue(frame.getRootName() + " has no location", frame.getSourceLocation() != null);
                }
            }
        }
    }

    @Test
    public void deepFramesKeepTheirLocations() throws IOException {
        // Past the spill depth, frames are resumed segments; their locations survive the yield.
        Source source = Source.newBuilder(SCHEME, """
                        (define (down n)
                          (if (= n 0)
                              (car n)
                              (+ 1 (down (- n 1)))))
                        (down 200)
                        """, "deep.scm").build();
        try (Context context = Context.create(SCHEME)) {
            List<String> frames = locations(error(context, source));
            // The frame that called car (in tail position) is down's recursive call site.
            assertTrue(frames.toString(), frames.contains("deep.scm:4:12"));
        }
    }

    @Test
    public void errorsInLibrariesNameTheLibraryFile() throws IOException {
        Path lib = folder.getRoot().toPath().resolve("lib");
        Files.createDirectories(lib);
        Files.writeString(lib.resolve("broken.sld"), """
                        (define-library (lib broken)
                          (import (scheme base))
                          (export first-of)
                          (begin
                            (define (first-of x)
                              (+ 0 (car x)))))
                        """, StandardCharsets.UTF_8);
        try (Context context = SchemeMain.newContext(List.of(folder.getRoot().getPath())).build()) {
            Source source = Source.newBuilder(SCHEME, "(import (lib broken))\n(first-of 5)\n", "main.scm").build();
            List<String> frames = locations(error(context, source));
            assertTrue(frames.toString(), frames.stream().anyMatch(f -> f.endsWith("broken.sld:6:12")));
            assertTrue(frames.toString(), frames.contains("main.scm:2:1"));
            // A syntax error in a library names the library's file, line and column.
            Files.writeString(lib.resolve("bad.sld"), "(define-library (lib bad)\n  (import (scheme base))\n  (begin (if)))\n", StandardCharsets.UTF_8);
            PolyglotException e = error(context, Source.newBuilder(SCHEME, "(import (lib bad))", "uses-bad.scm").build());
            assertTrue(e.getMessage(), e.getMessage().contains("bad.sld, line 3, column 10"));
        }
    }

    @Test
    public void syntaxErrorsNameTheFile() throws IOException {
        try (Context context = Context.create(SCHEME)) {
            PolyglotException e = error(context, Source.newBuilder(SCHEME, "(display 1)\n  (lambda (x x) x)", "dup.scm").build());
            assertEquals(true, e.getMessage().contains("(dup.scm, line 2, column 3)"));
        }
    }
}
