    @Test
    public void aLibrarysMacroIsLocatedOnlyInTheUsersFile() throws IOException {
        // Every tagged node of the program's roots is in the program's file: a library's template
        // (the prelude's, a user's library's) is in the library's file, where nothing of the
        // program is, in the outermost root as in a procedure's.
        Path lib = folder.getRoot().toPath().resolve("lib");
        Files.createDirectories(lib);
        Files.writeString(lib.resolve("mac.sld"), """
                        (define-library (lib mac)
                          (import (scheme base))
                          (export first-of)
                          (begin
                            (define (helper x) (list (car x)))
                            (define-syntax first-of
                              (syntax-rules ()
                                ((_ x) (list (helper x) 'from-lib))))))
                        """, StandardCharsets.UTF_8);
        Source source = Source.newBuilder(SCHEME, """
                        (import (scheme base) (lib mac))
                        (define-record-type point (make-point x) point? (x point-x))
                        (do ((i 0 (+ i 1))) ((= i 1)) (first-of '(1)))
                        (first-of '(2))
                        (define (f y)
                          (do ((i 0 (+ i 1))) ((= i 1)) (first-of y))
                          (first-of y))
                        (f 5)
                        """, "main.scm").build();
        try (Context context = SchemeMain.newContext(List.of(folder.getRoot().getPath())).build()) {
            SectionRecorder recorder = context.getEngine().getInstruments().get(SectionRecorder.ID).lookup(SectionRecorder.class);
            PolyglotException e = error(context, source);
            List<SectionRecorder.Loaded> program = recorder.loaded.stream().filter(l -> l.rootAt().startsWith("main.scm:") && !l.root().equals("<prompt>")).toList();
            assertTrue(program.toString(), program.size() > 10);
            assertEquals(List.of(), program.stream().filter(l -> !l.at().startsWith("main.scm:")).toList());
            // helper's error, called from the template in do's loop in f: helper's frame in the
            // library, the loop's at the use.
            assertEquals(e.getMessage(), "mac.sld:5:30", where(e.getSourceLocation()));
            assertEquals(List.of("helper mac.sld:5:30", "<lambda@main.scm:6:3> main.scm:6:33", "f main.scm:6:3", "<program> main.scm:8:1"), frames(e));
        }
    }

    /** "name file:line:column" for each guest frame with a location, but the root prompt's. */
    private static List<String> frames(PolyglotException e) {
        List<String> result = new ArrayList<>();
        for (PolyglotException.StackFrame frame : e.getPolyglotStackTrace()) {
            if (frame.isGuestFrame() && frame.getSourceLocation() != null && !frame.getRootName().equals("<prompt>")) {
                result.add(frame.getRootName() + " " + where(frame.getSourceLocation()));
            }
        }
        return result;
    }
