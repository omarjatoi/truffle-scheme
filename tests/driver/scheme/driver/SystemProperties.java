package scheme.driver;

import java.io.IOException;
import java.io.InputStream;
import java.lang.classfile.ClassFile;
import java.lang.classfile.ClassModel;
import java.lang.classfile.CodeModel;
import java.lang.classfile.MethodModel;
import java.lang.classfile.instruction.InvokeInstruction;
import java.lang.module.ModuleFinder;
import java.lang.module.ModuleReader;
import java.lang.module.ModuleReference;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.Set;
import java.util.stream.Stream;

/**
 * Test: the language reads no system property of its own (design.md D17, "Constant options"; plan.md
 * M11-07). A switch fixed for the process is a constant option, {@code @Option(constant = true)},
 * whose descriptors' class (generated by Truffle's option processor, {@code *OptionDescriptors})
 * reads {@code -Dpolyglot.<name>}, and lists and validates it like any option. Reads every class of
 * the {@code --modules} from {@code --module-path} and fails on a call that reads a system property
 * outside those generated classes: {@code System.getProperty} and {@code getProperties},
 * {@code Boolean.getBoolean}, {@code Integer.getInteger} and {@code Long.getLong}.
 *
 * <p>
 * {@code --modules=scheme}
 */
public final class SystemProperties {

    /** The methods that read system properties, by their class's internal name. */
    private static final Map<String, Set<String>> READS = Map.of(
                    "java/lang/System", Set.of("getProperty", "getProperties"),
                    "java/lang/Boolean", Set.of("getBoolean"),
                    "java/lang/Integer", Set.of("getInteger"),
                    "java/lang/Long", Set.of("getLong"));
    /** What the option processor names the descriptors' class of a class with options. */
    private static final String GENERATED = "OptionDescriptors";

    private SystemProperties() {
    }

    public static void main(String[] args) throws IOException {
        Launch launch = new Launch(args);
        ModuleFinder finder = ModuleFinder.of(Arrays.stream(launch.modulePath.split(":")).map(Path::of).toArray(Path[]::new));
        List<String> errors = new ArrayList<>();
        int classes = 0;
        int generated = 0;
        for (String name : launch.option("modules").split(",")) {
            Optional<ModuleReference> found = finder.find(name);
            if (found.isEmpty()) {
                errors.add(name + ": not on the module path");
                continue;
            }
            try (ModuleReader reader = found.get().open(); Stream<String> entries = reader.list()) {
                for (String entry : entries.filter(e -> e.endsWith(".class") && !e.equals("module-info.class")).toList()) {
                    ClassModel model;
                    try (InputStream in = reader.open(entry).orElseThrow()) {
                        model = ClassFile.of().parse(in.readAllBytes());
                    }
                    classes++;
                    String cls = model.thisClass().asInternalName();
                    List<String> reads = reads(model);
                    if (cls.endsWith(GENERATED) && !reads.isEmpty()) {
                        generated++;
                        Launch.log(name + ": " + cls.replace('/', '.') + " (generated) reads -Dpolyglot.<option> for its constant options");
                    } else {
                        reads.forEach(r -> errors.add(name + ": " + cls.replace('/', '.') + "." + r));
                    }
                }
            }
        }
        if (classes == 0) {
            errors.add("no classes read");
        }
        if (generated == 0) {
            errors.add("no generated option descriptors read a constant option's system property: is the check still looking at the right calls?");
        }
        if (!errors.isEmpty()) {
            errors.forEach(e -> Launch.log("FAIL " + e + " reads a system property: make it a constant option (design.md D17, \"Constant options\")"));
            System.exit(1);
        }
        Launch.log("ok: " + classes + " classes read no system property but through constant options");
    }

    /** The calls of a class's methods that read a system property: {@code method calls Owner.name}. */
    private static List<String> reads(ClassModel model) {
        List<String> reads = new ArrayList<>();
        for (MethodModel method : model.methods()) {
            Optional<CodeModel> code = method.code();
            if (code.isEmpty()) {
                continue;
            }
            code.get().forEach(element -> {
                if (element instanceof InvokeInstruction invoke) {
                    String owner = invoke.owner().asInternalName();
                    String called = invoke.name().stringValue();
                    if (READS.getOrDefault(owner, Set.of()).contains(called)) {
                        reads.add(method.methodName().stringValue() + " calls " + owner.replace('/', '.') + "." + called);
                    }
                }
            });
        }
        return reads;
    }
}
